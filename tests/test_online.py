@online
class EndToEnd(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.root = project(E2E_FILES)
        cls.proc = run_cli(cls.root, "--format", "json", "--fail-on", "never", "--lang", "en")
        cls.doc = json.loads(cls.proc.stdout) if cls.proc.returncode == 0 else None
        cls.dep = {}
        for f in (cls.doc or {}).get("findings", []):
            if f["rule"] == "DEP001":
                cls.dep[(f["data"]["ecosystem"], f["data"]["pkg"])] = f

    def setUp(self):
        self.assertEqual(self.proc.returncode, 0, self.proc.stderr)
        self.assertNotIn("Traceback", self.proc.stderr)

    def test_sources_used(self):
        src = self.doc["sources"]
        self.assertIs(src.get("osv"), True)
        self.assertRegex(str(src.get("kev")), r"^\d{4}\.\d{2}\.\d{2}$")
        self.assertIs(src.get("epss"), True)
        self.assertGreaterEqual(src.get("packages", 0), len(E2E_EXPECT))
        self.assertFalse({"osv_error", "kev_error"} & set(src), src)

    def test_dep001_per_ecosystem(self):
        for eco, pkg, rel, cve, min_fixed, in_kev in E2E_EXPECT:
            with self.subTest(pkg=f"{eco}:{pkg}"):
                f = self.dep.get((eco, pkg))
                self.assertIsNotNone(f, sorted(self.dep))
                self.assertEqual(f["file"], rel)
                self.assertIsNotNone(f["line"])
                vuln = next((v for v in f["data"]["vulns"] if v["id"] == cve), None)
                self.assertIsNotNone(vuln, [v["id"] for v in f["data"]["vulns"]])
                self.assertGreaterEqual(vt(vuln["fixed"]), vt(min_fixed))
                self.assertGreaterEqual(vt(f["data"]["fixed"]), vt(min_fixed))
                self.assertTrue(f["refs"][0].startswith("https://osv.dev/vulnerability/"))
                if in_kev:
                    self.assertIn("kev", f["tags"])
                    self.assertEqual(f["severity"], "critical")
                    self.assertEqual(vuln["kev"], cve)
        self.assertEqual([f["rule"] for f in self.doc["findings"] if f["rule"] in ("DEP002", "DEP003")], [])

    def test_mcp_remote_from_mcp_json_is_critical(self):
        f = self.dep[("npm", "mcp-remote")]
        self.assertEqual(f["severity"], "critical")
        self.assertEqual(f["data"]["version"], "0.1.15")

    def test_go_fixed_version_keeps_v_prefix(self):
        f = self.dep[("Go", "golang.org/x/net")]
        self.assertRegex(f["data"]["fixed"], r"^v\d")

    def test_fail_on_high_exits_1_and_text_lists_sources(self):
        r = run_cli(self.root, "--format", "text", "--lang", "en", "--no-color", "--fail-on", "high")
        self.assertEqual(r.returncode, 1, r.stderr)
        line = next(x for x in r.stdout.splitlines() if x.startswith("Sources:"))
        for name in ("package(s) checked", "OSV.dev", "CISA KEV", "EPSS (FIRST)"):
            self.assertIn(name, line)


