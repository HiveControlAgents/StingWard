def _dead_port():
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    return port


@online
class NetworkFailure(unittest.TestCase):
    def test_dead_proxy_reports_osv_did_not_respond(self):
        root = project({"package-lock.json": npm_lock([("lodash", "4.17.15")])})
        env = dict(os.environ)
        for k in ("NO_PROXY", "no_proxy"):
            env.pop(k, None)
        dead = f"http://127.0.0.1:{_dead_port()}"
        for k in ("HTTPS_PROXY", "https_proxy", "HTTP_PROXY", "http_proxy"):
            env[k] = dead
        env["STINGWARD_CACHE"] = _tmpdir("stingward-online-emptycache-")  # cache vazio: tem que ir à rede
        out_json = os.path.join(_tmpdir(), "report.json")
        r = run_cli(root, "--format", "text", "--lang", "en", "--no-color", "--fail-on", "never", "--json", out_json,
                    env=env, timeout=180)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertNotIn("Traceback", r.stderr)
        self.assertIn("Sources: OSV.dev did not respond: dependencies were not checked", r.stdout)
        with open(out_json, encoding="utf-8") as fh:
            doc = json.load(fh)
        self.assertIn("osv_error", doc["sources"])
        self.assertNotIn("osv", doc["sources"])
        self.assertEqual(doc["sources"]["packages"], 1)
        self.assertEqual([f["rule"] for f in doc["findings"] if f["rule"].startswith("DEP")], [])


