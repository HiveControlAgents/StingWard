@online
class OsvQuery(unittest.TestCase):
    def test_known_vulnerable_versions(self):
        ids = vulndb.osv_query([(e, n, v) for e, n, v, *_ in KNOWN])
        self.assertEqual(len(ids), len(KNOWN))
        docs = vulndb.osv_vulns([k[3] for k in KNOWN])
        for (eco, name, version, osv_id, cve, min_fixed), got in zip(KNOWN, ids):
            with self.subTest(pkg=f"{eco}:{name}@{version}"):
                self.assertIn(osv_id, got)
                doc = docs.get(osv_id)
                self.assertIsNotNone(doc, f"GET /v1/vulns/{osv_id} falhou")
                self.assertIn(cve, [doc["id"]] + (doc.get("aliases") or []))
                fixed = vulndb.fixed_version(doc, eco, name, version)
                self.assertIsNotNone(fixed)
                self.assertGreaterEqual(vt(fixed), vt(min_fixed))
                sev, _ = vulndb.severity_of(doc)
                self.assertIn(sev, ("low", "medium", "high", "critical"))

    def test_batches_of_500_keep_order(self):
        # 1001 consultas = 3 lotes. Pacotes reais nas bordas dos lotes; o resto não existe.
        pkgs = [("npm", f"stingward-online-synthetic-{i:04d}", "1.0.0") for i in range(1001)]
        real = {0: ("npm", "lodash", "4.17.15", "GHSA-p6mc-m468-83gw"),
                500: ("npm", "minimist", "1.2.0", "GHSA-xvch-5gv4-984h"),
                1000: ("npm", "mcp-remote", "0.1.15", "GHSA-6xpm-ggf7-wc3p")}
        for i, (e, n, v, _) in real.items():
            pkgs[i] = (e, n, v)
        out = vulndb.osv_query(pkgs)
        self.assertEqual(len(out), 1001)
        for i, ids in enumerate(out):
            if i in real:
                self.assertIn(real[i][3], ids, i)
            else:
                self.assertEqual(ids, [], i)


