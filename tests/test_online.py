def _skip_if_nvd_unavailable(test, cve):
    """nvd_severity engole erros de rede; aqui descobrimos se foi limite de taxa da NVD."""
    headers = {"apiKey": os.environ["NVD_API_KEY"]} if os.environ.get("NVD_API_KEY") else None
    try:
        net.fetch_json(vulndb.NVD_URL.format(cve), timeout=30, headers=headers)
    except net.NetError as e:
        if re.search(r"\b(403|429|500|502|503|504)\b", str(e)):
            test.skipTest(f"NVD recusou ou caiu (limite de taxa sem NVD_API_KEY?): {e}")
        raise


