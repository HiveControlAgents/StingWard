def npm_lock(pkgs):
    packages = {"": {"name": "stingward-online-fixture", "version": "1.0.0",
                     "dependencies": {n: v for n, v in pkgs}}}
    for n, v in pkgs:
        packages[f"node_modules/{n}"] = {"version": v, "resolved": f"https://registry.npmjs.org/{n}/-/{n.rsplit('/', 1)[-1]}-{v}.tgz",
                                         "license": "MIT"}
    return json.dumps({"name": "stingward-online-fixture", "version": "1.0.0", "lockfileVersion": 3,
                       "requires": True, "packages": packages}, indent=2) + "\n"


def cargo_lock(pkgs):
    out = ["# This file is automatically @generated by Cargo.", "# It is not intended for manual editing.", "version = 3", ""]
    for n, v in pkgs:
        out += ["[[package]]", f'name = "{n}"', f'version = "{v}"',
                'source = "registry+https://github.com/rust-lang/crates.io-index"',
                'checksum = "fe0f37c9e8f3c5a4a66ad655a93c74daac4ad00c441533bf5c6e7990bb42604e"', ""]
    return "\n".join(out)


def gemfile_lock(pkgs):
    specs = "".join(f"    {n} ({v})\n      activesupport (= {v})\n" for n, v in pkgs)
    deps = "".join(f"  {n} (= {v})\n" for n, v in pkgs)
    return (f"GEM\n  remote: https://rubygems.org/\n  specs:\n{specs}\nPLATFORMS\n  ruby\n\n"
            f"DEPENDENCIES\n{deps}\nBUNDLED WITH\n   2.4.10\n")


def composer_lock(pkgs, dev=()):
    entry = lambda n, v: {"name": n, "version": v, "source": {"type": "git", "url": f"https://github.com/{n}.git"},
                          "type": "library", "license": ["MIT"]}
    return json.dumps({"_readme": ["This file locks the dependencies of your project to a known state"],
                       "content-hash": "0" * 32, "packages": [entry(n, v) for n, v in pkgs],
                       "packages-dev": [entry(n, v) for n, v in dev], "minimum-stability": "stable"}, indent=4) + "\n"


def mcp_json(spec):
    return json.dumps({"mcpServers": {"remote": {"command": "npx", "args": ["-y", spec, "https://mcp.example.com/sse"]}}}, indent=2) + "\n"


