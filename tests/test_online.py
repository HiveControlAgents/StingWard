ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

_DIRS = []
_SAVED_ENV = {}


def setUpModule():
    if not ONLINE:
        return
    # Cache novo a cada execução: nada pode vir de uma resposta antiga em ~/.cache/stingward.
    cache = _tmpdir("stingward-online-cache-")
    _SAVED_ENV["STINGWARD_CACHE"] = os.environ.get("STINGWARD_CACHE")
    os.environ["STINGWARD_CACHE"] = cache


def tearDownModule():
    for k, v in _SAVED_ENV.items():
        if v is None:
            os.environ.pop(k, None)
        else:
            os.environ[k] = v
    for d in _DIRS:
        d.cleanup()


def _tmpdir(prefix="stingward-online-"):
    d = tempfile.TemporaryDirectory(prefix=prefix)
    _DIRS.append(d)
    return d.name


def project(files):
    root = _tmpdir()
    for rel, content in files.items():
        p = os.path.join(root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(content)
    return root


def vt(v):
    """Versão como tupla de números, só para comparar >= nas asserções (independe de vulndb._vkey)."""
    return tuple(int(x) for x in re.findall(r"\d+", v.lstrip("vV").split("-")[0].split("+")[0]))


def run_cli(target, *args, env=None, timeout=300):
    cmd = [sys.executable, "-m", "stingward", target] + list(args)
    return subprocess.run(cmd, cwd=ROOT, env=env or dict(os.environ), capture_output=True, text=True, timeout=timeout)


def deps_scan(files):
    ctx, findings = scan.run(project(files), offline=False, only={"deps"})
    return ctx, findings


def by_pkg(findings, rule):
    out = {}
    for f in findings:
        if f.rule == rule:
            out.setdefault(f.params["pkg"], []).append(f)
    return out


