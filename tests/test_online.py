@online
class DepsCheck(unittest.TestCase):
    def test_safe_recent_versions_have_no_dep001(self):
        # Sem falhas no OSV em 2026-10-19. Se alguma ganhar CVE nova, troque pela versão seguinte.
        ctx, findings = deps_scan({"package-lock.json": npm_lock([("lodash", "4.18.1")]),
                                   "requirements.txt": "requests==2.33.1\n"})
        self.assertTrue(ctx.sources.get("osv"))
        self.assertEqual(ctx.sources.get("packages"), 2)
        self.assertEqual([f.rule for f in findings], [])

    @classmethod
    def _malicious(cls):
        if not hasattr(cls, "_mal"):
            cls._mal = deps_scan({"package-lock.json": npm_lock([("discord.dll", "1.0.0"), ("flatmap-stream", "0.1.1"),
                                                                 ("crossenv", "1.0.0")]),
                                  "requirements.txt": "aiohttpp==1.0.0\n"})[1]
        return cls._mal

    def test_malicious_packages_are_dep002(self):
        dep002 = by_pkg(self._malicious(), "DEP002")
        for pkg, mal_id in (("discord.dll", "MAL-2025-18479"), ("aiohttpp", "MAL-2023-1579"), ("flatmap-stream", "MAL-2025-20690")):
            with self.subTest(pkg=pkg):
                self.assertIn(pkg, dep002)
                f = next(x for x in dep002[pkg] if x.params["vuln_id"] == mal_id)
                self.assertEqual(f.severity, "critical")
                self.assertEqual(f.tags, ["malicious"])
                self.assertEqual(f.refs, [f"https://osv.dev/vulnerability/{mal_id}"])
        self.assertNotIn("discord.dll", by_pkg(self._malicious(), "DEP001"))

    def test_malicious_package_not_also_reported_as_vulnerable(self):
        if "flatmap-stream" not in by_pkg(self._malicious(), "DEP002"):
            self.skipTest("pré-condição: OSV não lista mais MAL- para flatmap-stream")
        dep001 = by_pkg(self._malicious(), "DEP001")
        self.assertNotIn("flatmap-stream", set(dep001), [v["osv"] for f in dep001.get("flatmap-stream", []) for v in f.params["vulns"]])
        self.assertEqual(len(by_pkg(self._malicious(), "DEP002")["flatmap-stream"]), 1)  # MAL + 2 GHSA de malware: um achado só
        self.assertIn("GHSA-9x64-5r7x-2q53", by_pkg(self._malicious(), "DEP002")["flatmap-stream"][0].params["advisories"])

    def test_github_malware_advisory_without_mal_record_is_dep002(self):
        # crossenv só tem o aviso do GitHub (CWE-506, "crossenv is malware"), sem registro MAL- no OSV em 2026-10-19
        dep002 = by_pkg(self._malicious(), "DEP002")
        self.assertIn("crossenv", dep002)
        self.assertIn("GHSA-c2m4-w5hm-vqjw", dep002["crossenv"][0].params["advisories"])
        self.assertEqual(dep002["crossenv"][0].severity, "critical")
        self.assertNotIn("crossenv", by_pkg(self._malicious(), "DEP001"))

    def test_kev_unavailable_still_reports_vulns(self):
        # OSV de verdade, KEV num endereço que responde 403: o scan segue sem a marcação KEV.
        with mock.patch.object(vulndb, "KEV_URL", "https://www.cisa.gov/sites/default/files/feeds/stingward-online-missing.json"):
            ctx, findings = deps_scan({"package-lock.json": npm_lock([("lodash", "4.17.15")])})
        self.assertTrue(ctx.sources.get("osv"))
        self.assertIn("kev_error", ctx.sources)
        self.assertNotIn("kev", ctx.sources)
        dep = by_pkg(findings, "DEP001")["lodash"][0]
        self.assertIn("CVE-2020-8203", [v["id"] for v in dep.params["vulns"]])
        self.assertNotIn("kev", dep.tags)


