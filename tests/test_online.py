@online
class NvdSeverity(unittest.TestCase):
    def test_nvd_score_for_cve(self):
        score = vulndb.nvd_severity("CVE-2021-44228")
        if score is None:
            _skip_if_nvd_unavailable(self, "CVE-2021-44228")
            self.fail("a NVD respondeu, mas nvd_severity devolveu None")
        self.assertEqual(score, 10.0)
        self.assertEqual(vulndb.score_to_sev(score), "critical")

    def test_scan_falls_back_to_nvd_when_osv_has_no_severity(self):
        real = vulndb.osv_vulns

        def without_severity(ids):
            docs = real(ids)
            for d in docs.values():
                d.pop("severity", None)
                d.pop("database_specific", None)
                for a in d.get("affected") or []:
                    a.pop("database_specific", None)
                    a.pop("ecosystem_specific", None)
            return docs

        with mock.patch.object(vulndb, "osv_vulns", side_effect=without_severity):
            ctx, findings = deps_scan({"package-lock.json": npm_lock([("mcp-remote", "0.1.15")])})
        dep = by_pkg(findings, "DEP001")["mcp-remote"][0]
        vuln = next(x for x in dep.params["vulns"] if x["id"] == "CVE-2025-6514")
        if vuln["cvss"] is None:
            _skip_if_nvd_unavailable(self, "CVE-2025-6514")
            self.fail("a NVD respondeu, mas o scan não usou a nota dela")
        self.assertTrue(ctx.sources.get("nvd"))
        self.assertGreaterEqual(vuln["cvss"], 7.0)  # 9.6 (CNA JFrog) em 2026-10
        self.assertIn(dep.severity, ("high", "critical"))


